import { html, raw, icon, mount } from "../ui.js";
import { REPO_URL } from "../config.js";

let cache;
/** results.json is generated at build time from docs/backtest.json. Missing → throws → "Results pending". */
export async function loadResults(fetchImpl = fetch) {
  if (cache) return cache;
  const res = await fetchImpl("/data/results.json", { cache: "no-cache" });
  if (!res.ok) throw new Error("no results");
  const data = await res.json();
  if (!data || !Array.isArray(data.splits) || data.splits.length === 0) throw new Error("empty results");
  cache = data;
  return data;
}

const MODELS = [
  ["baseline", "Past-late-rate baseline"],
  ["tabpfn35", "TabPFN-3.5"],
  ["tabpfnv2", "TabPFN v2"],
];

function bestKey(split, metric) {
  let best = null;
  for (const [k] of MODELS) {
    const v = split[k]?.[metric];
    if (v == null) continue;
    if (best === null) best = k;
    else {
      const b = split[best][metric];
      if (metric === "auc" ? v > b : v < b) best = k;
    }
  }
  return best;
}

const f3 = (v) => (v == null ? "—" : Number(v).toFixed(3));

export function resultsTable(data, { compact = false } = {}) {
  const metrics = compact ? ["auc"] : ["auc", "brier"];
  return html`
    <div class="table-wrap">
      <table class="table results-table">
        <caption class="sr-only">Synthetic backtest: AUC${compact ? "" : " and Brier score"} by training size and model</caption>
        <thead>
          <tr>
            <th scope="col">Train N</th>
            ${compact ? "" : html`<th scope="col" class="num">Test N</th>`}
            ${MODELS.map(([, label]) => metrics.map((m) => html`<th scope="col" class="num">${label}${compact ? "" : raw(`<br><span class="xs">${m.toUpperCase()}</span>`)}</th>`))}
          </tr>
        </thead>
        <tbody>
          ${data.splits.map((s) => {
            const bests = Object.fromEntries(metrics.map((m) => [m, bestKey(s, m)]));
            return html`<tr>
              <th scope="row">${s.n_train}</th>
              ${compact ? "" : html`<td class="num">${s.n_test}</td>`}
              ${MODELS.map(([k]) => metrics.map((m) => html`<td class="num ${bests[m] === k ? "best" : ""}">${f3(s[k]?.[m])}</td>`))}
            </tr>`;
          })}
        </tbody>
      </table>
    </div>
    <p class="results-foot">
      <span class="badge badge-accent">synthetic benchmark</span>
      ${data.disclaimer || "Synthetic data — pipeline evidence, not evidence about real clients."}
      Generated ${data.generated_at ? new Date(data.generated_at).toLocaleDateString(undefined, { dateStyle: "medium" }) : "—"}${data.packages?.tabpfn ? ` · tabpfn ${data.packages.tabpfn}` : ""}. ${compact ? "Bold = best AUC per row." : "Bold = best per metric per row (AUC higher is better; Brier lower is better)."}
    </p>`;
}

export async function renderResults(main) {
  mount(
    main,
    html`<section class="section wrap-text prose">
      <p class="eyebrow">Results</p>
      <h1>Every number here came from a real run.</h1>
      <p class="lede">All benchmarks use the <strong>synthetic</strong> ledger generated by <code>db/generate_synthetic.py</code>. They validate the pipeline; they say nothing about real payment behaviour. Commands and dates are in <a href="${REPO_URL}/blob/main/docs/results.md" target="_blank" rel="noopener">docs/results.md</a>.</p>

      <h2>Backtest — P(paid &gt;7 days late), time split</h2>
      <p class="muted small">Features are point-in-time (only history before each receivable’s issue date). A unit test fails if future rows leak. Label = paid more than 7 days after due date.</p>
      <div id="results-table"><span class="skeleton h-8 w-100"></span></div>

      <h2>How to read it</h2>
      <ul>
        <li><strong>The baseline is strong.</strong> “This client’s past late rate” wins at 50 training rows and stays close at 100. TabPFN only catches up around 300.</li>
        <li><strong>So the product shows both.</strong> The queue ranks by TabPFN risk, but the “why” column is the baseline stats — days overdue, prior late rate — which you can check yourself.</li>
        <li><strong>Licences differ.</strong> TabPFN-3.5 weights are non-commercial (benchmark/demo only). TabPFN v2 weights are the permissive Prior Labs licence. Built with PriorLabs-TabPFN.</li>
      </ul>

      <h2>Other measurements</h2>
      <p class="muted small">Latency, memory and model-bench figures are recorded with their commands in <a href="${REPO_URL}/blob/main/docs/results.md" target="_blank" rel="noopener">docs/results.md</a> and are not duplicated here, so this page can never drift from the source.</p>

      <h2>What we did not measure</h2>
      <ul>
        <li>No public payments dataset with a clearly verified licence was found inside the time budget — so there is no real-data backtest. That is a limitation, not a footnote.</li>
        <li>Self-hosted Ollama latency is pending the benchmark droplet.</li>
      </ul>
    </section>`,
  );
  const slot = main.querySelector("#results-table");
  try {
    mount(slot, resultsTable(await loadResults()));
  } catch {
    mount(slot, html`<div class="notice notice-info">${icon("info")}<p><strong>Results pending.</strong> This build has no <code>data/results.json</code>. Run the backtest (<code>apps/risk-sidecar/backtest.py</code>) and rebuild the site to populate it.</p></div>`);
  }
}
